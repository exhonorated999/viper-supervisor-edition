// Bundle the LAN node (lan-node/server.mjs + its deps, incl. `ws`) into a
// single self-contained CommonJS file so the PACKAGED Electron app can spawn
// it as a sidecar via utilityProcess — no node_modules ship with the app.
//
// Output: lan-dist/server.cjs  (referenced by electron-builder extraResources
// and by electron/main.cjs at runtime when app.isPackaged).
//
// Run:  node scripts/build-lan-node.mjs   (wired into npm run build:lan)
// ---------------------------------------------------------------------------
import { build } from "esbuild";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

await build({
  entryPoints: [path.join(root, "lan-node", "server.mjs")],
  outfile: path.join(root, "lan-dist", "server.cjs"),
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node18",
  // ws pulls optional native addons (bufferutil / utf-8-validate); they are
  // optional at runtime (pure-JS fallback), so mark them external and let the
  // require fail gracefully inside ws rather than break the bundle.
  external: ["bufferutil", "utf-8-validate"],
  banner: {
    js: "// V.I.P.E.R. LAN Node — bundled sidecar (generated by scripts/build-lan-node.mjs). Do not edit.",
  },
  logLevel: "info",
});

console.log("  ✓ lan-dist/server.cjs written");
